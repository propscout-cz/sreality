"""The platform checks' pg_cron reads, executed: finished runs only, each job's own week, 2 of 3, whole weeks.

CI's replay has no pg_cron, so each test stubs the `cron` schema (the columns the checks read, typed as pg_cron's)
inside a transaction that always rolls back, seeds runs relative to that transaction's now(), and runs
`_CRON_JOBS_SQL`, `_CAPACITY_CRON_SQL` and `_CAPACITY_REFERENCE_SQL` through psycopg with the parameters the checks
send, then the cells they feed. The artifact read, the jobs check's other verdict computed in SQL, runs on the
replay's own `derived_artifacts` with the GitHub delivery slack the check sends. Runs in CI's migrations lane
(`TEST_DATABASE_URL`, `DB_RAILS_REQUIRED=1`); skipped locally.
"""

from __future__ import annotations

import datetime as _dt
import os
from typing import Any

import pytest

from scripts.checks import platform as plat
from scripts.verify_pipeline import THRESHOLDS

_DB_URL = os.environ.get("TEST_DATABASE_URL")
_REQUIRED = os.environ.get("DB_RAILS_REQUIRED") == "1"
_UTC = _dt.timezone.utc

pytestmark = pytest.mark.skipif(
    not _DB_URL and not _REQUIRED,
    reason="TEST_DATABASE_URL not set — this rail runs in CI's migrations lane",
)

# The two tables the checks read, with pg_cron's names and types for every column they touch.
_STUB = """
create schema cron;
create table cron.job (
  jobid bigint generated by default as identity primary key,
  jobname name, schedule text, command text, active boolean);
create table cron.job_run_details (
  runid bigint generated by default as identity primary key,
  jobid bigint, status text, return_message text, start_time timestamptz, end_time timestamptz);
"""


@pytest.fixture()
def conn():
    """One connection in one transaction, always rolled back, holding the cron stub."""
    if not _DB_URL:
        pytest.fail("DB_RAILS_REQUIRED=1 but TEST_DATABASE_URL is not set — the migrations lane is "
                    "misconfigured and this rail would otherwise have skipped green.")
    import psycopg

    connection = psycopg.connect(_DB_URL)
    try:
        exists = connection.execute("select to_regnamespace('cron') is not null").fetchone()[0]
        if exists:
            pytest.fail("this database has a cron schema (pg_cron): the rail stubs one, so it runs "
                        "against CI's replay, which has none")
        connection.execute(_STUB)
        yield connection
    finally:
        connection.rollback()
        connection.close()


def _now(conn: Any) -> _dt.datetime:
    """The transaction's now(), the clock every window in the checks' SQL is measured on."""
    return conn.execute("select now()").fetchone()[0]


def _job(conn: Any, name: str, *, command: str = "select 1;", active: bool = True) -> int:
    return conn.execute("insert into cron.job (jobname, schedule, command, active) "
                        "values (%s, '*/15 * * * *', %s, %s) returning jobid",
                        (name, command, active)).fetchone()[0]


def _run(conn: Any, jobid: int, start: _dt.datetime, status: str, seconds: float | None,
         message: str = "") -> None:
    """One run begun at `start`; `seconds` None leaves it unfinished (running, or cut off by a restart)."""
    end = None if seconds is None else start + _dt.timedelta(seconds=seconds)
    conn.execute("insert into cron.job_run_details (jobid, status, return_message, start_time, end_time) "
                 "values (%s, %s, %s, %s, %s)", (jobid, status, message, start, end))


def _by_name(rows: list[tuple[Any, ...]]) -> dict[str, tuple[Any, ...]]:
    return {row[0]: row for row in rows}


def _by_subject(cells: list[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    return {cell["subject"]: cell for cell in cells}


def test_the_cron_arm_counts_finished_runs_only_and_quotes_a_finished_failure(conn):
    """pg_cron marks a run a server restart cut off failed and leaves its end_time NULL, and a running
    run is unfinished too: neither takes a slot of the last three, counts in 24 h or is the failure
    quoted. Two of the newest three finished runs failed is the Problem."""
    now = _now(conn)

    def ago(minutes: float) -> _dt.datetime:
        return now - _dt.timedelta(minutes=minutes)

    restarted = _job(conn, "w3-restarted")
    for minutes, status, seconds, message in (
            (5, "succeeded", 2.0, "1 row"),
            (20, "failed", None, "server restarted"),
            (35, "failed", 300.0, "ERROR:  canceling statement due to statement timeout"),
            (50, "succeeded", 2.0, "1 row"),
            (65, "failed", 4.0, "ERROR:  deadlock detected")):
        _run(conn, restarted, ago(minutes), status, seconds, message)
    flapping = _job(conn, "w3-flapping")
    for minutes, status, seconds in ((3, "running", None), (18, "failed", 60.0), (33, "succeeded", 2.0),
                                     (48, "failed", 60.0), (63, "succeeded", 2.0)):
        _run(conn, flapping, ago(minutes), status, seconds, "ERROR:  boom" if status == "failed" else "")

    rows = _by_name(conn.execute(plat._CRON_JOBS_SQL).fetchall())
    _, active, newest, starts, gap, last3, failed_24h, failed_at, failure = rows["w3-restarted"]
    assert (active, newest, starts, gap) == (True, ago(5), 5, 900.0)
    assert (last3, failed_24h) == (["succeeded", "failed", "succeeded"], 2)
    assert (failed_at, failure) == (ago(35), "ERROR:  canceling statement due to statement timeout")
    _, _, newest, _, _, last3, failed_24h, failed_at, _ = rows["w3-flapping"]
    assert newest == ago(3), "a running run is still the newest start"
    assert (last3, failed_24h, failed_at) == (["failed", "succeeded", "failed"], 2, ago(18))

    cells, unread = plat._cron_cells(conn, THRESHOLDS, now)
    by = _by_subject(cells)
    assert unread is None
    assert by["cron/w3-flapping"]["status"] == "fail"
    assert by["cron/w3-flapping"]["message"] == "2 of its last 3 runs failed: ERROR: boom"
    assert by["cron/w3-restarted"]["status"] == "warn"
    assert by["cron/w3-restarted"]["message"].endswith(
        ": ERROR: canceling statement due to statement timeout")


def test_each_job_is_measured_over_the_7_days_before_its_own_newest_start(conn):
    """A job that stopped firing 10 days ago is still read against its own last week (28 starts 6 h
    apart, the 7th day's edge excluded), so it is late on its own gap; a job that never ran is no
    verdict."""
    now = _now(conn)
    stopped = _job(conn, "w3-stopped")
    for k in range(41):  # every 6 h from 20 days ago until 10 days ago
        _run(conn, stopped, now - _dt.timedelta(days=10, hours=6 * k), "succeeded", 1.0)
    _job(conn, "w3-never-ran")

    rows = _by_name(conn.execute(plat._CRON_JOBS_SQL).fetchall())
    _, _, newest, starts, gap, last3, failed_24h, failed_at, failure = rows["w3-stopped"]
    assert newest == now - _dt.timedelta(days=10)
    assert (starts, gap, last3, failed_24h, failed_at, failure) == (
        28, 21600.0, ["succeeded"] * 3, 0, None, None)
    assert rows["w3-never-ran"][1:] == (True, None, 0, None, None, 0, None, None)

    by = _by_subject(plat._cron_cells(conn, THRESHOLDS, now)[0])
    assert by["cron/w3-stopped"]["status"] == "fail"
    assert by["cron/w3-stopped"]["message"] == ("no start for 10.0 d, over 3× its median start gap "
                                                "of 6.0 h")
    assert by["cron/w3-never-ran"]["status"] == "unknown"


def test_capacity_reads_finished_durations_over_24_hours_and_start_gaps_over_7_days(conn):
    """A finished red run is a duration like any other; a running one and one older than 24 h are
    not. The interval is the median gap between every start of the 7 days."""
    now = _now(conn)
    job = _job(conn, "w3-capacity", command="set statement_timeout='300s'; select 1;")
    for hours, status, seconds in ((1, "running", None), (2, "succeeded", 10.0), (3, "succeeded", 20.0),
                                   (4, "failed", 30.0), (5, "succeeded", 40.0),
                                   (30, "succeeded", 1000.0)):
        _run(conn, job, now - _dt.timedelta(hours=hours), status, seconds)

    rows = _by_name(conn.execute(plat._CAPACITY_CRON_SQL).fetchall())
    _, active, command, p50, p95, finished, gap = rows["w3-capacity"]
    assert (active, command, finished, gap) == (
        True, "set statement_timeout='300s'; select 1;", 4, 3600.0)
    assert (p50, p95) == (25.0, pytest.approx(38.5))

    thresholds = {**THRESHOLDS, "CAPACITY_REFERENCE_FROM": now.astimezone(_UTC).date()}
    cells, unread = plat._capacity_cron_cells(conn, thresholds, now)
    cell = _by_subject(cells)["cron/w3-capacity"]
    assert unread is None and cell["status"] == "ok"
    assert (cell["facts"]["finished_24h"], cell["facts"]["statement_timeout_s"]) == (4, 300.0)
    assert cell["facts"]["relative"].startswith("Not measured: ")


def test_the_reference_is_the_lowest_whole_weeks_p50_of_finished_runs_since_the_blessed_day(conn):
    """Weeks are counted from the blessed day, the week still running never counts, and neither does
    an unfinished run or one before the day: the reference an incident cannot erode."""
    now = _now(conn)
    day = (now - _dt.timedelta(days=15)).astimezone(_UTC).date()
    ref = _dt.datetime.combine(day, _dt.time(), tzinfo=_UTC)
    week, one_day = _dt.timedelta(days=7), _dt.timedelta(days=1)
    job = _job(conn, "w3-reference")
    for start, status, seconds in (
            (ref - one_day, "succeeded", 1.0),                       # before the blessed day
            (ref + one_day, "succeeded", 10.0), (ref + 2 * one_day, "succeeded", 20.0),
            (ref + 3 * one_day, "succeeded", 30.0),
            (ref + 4 * one_day, "failed", None),                     # week 0, cut off by a restart
            (ref + week, "succeeded", 3.0), (ref + week + one_day, "succeeded", 5.0),
            (ref + week + 2 * one_day, "succeeded", 7.0),
            (ref + week + 3 * one_day, "succeeded", 9.0),            # week 1
            (ref + 2 * week, "succeeded", 1.0),                      # the week still running
            (now - _dt.timedelta(hours=1), "succeeded", 30.0)):
        _run(conn, job, start, status, seconds)

    rows = conn.execute(plat._CAPACITY_REFERENCE_SQL, {"ref": ref}).fetchall()
    weeks = {int(n): p50 for name, n, p50 in rows if name == "w3-reference"}
    assert weeks == {0: 20.0, 1: 6.0}

    cells, unread = plat._capacity_cron_cells(conn, {**THRESHOLDS, "CAPACITY_REFERENCE_FROM": day}, now)
    cell = _by_subject(cells)["cron/w3-reference"]
    assert unread is None and cell["status"] == "warn"
    assert cell["facts"]["reference_p50_s"] == 6.0
    assert cell["message"] == (f"24 h p50 30 s is 5.0× its reference 6.0 s (its lowest weekly p50 "
                               f"since {day})")


def test_a_workflows_artifact_is_stale_only_past_its_budget_plus_githubs_delivery_slack(conn):
    """health_stale (migration 619) on the budget plus the slack the check sends for github-actions
    rows; any other host keeps the bare budget."""
    for name, host, budget, age in (("w3-gh-held", "github-actions", "30 hours", "40 hours"),
                                    ("w3-gh-stale", "github-actions", "30 hours", "49 hours"),
                                    ("w3-cron-stale", "pg_cron", "45 minutes", "50 minutes")):
        conn.execute("insert into derived_artifacts (name, producer, host, cadence, staleness_budget, "
                     "last_succeeded_at) values (%s, 'w3', %s, '0 * * * *', %s::interval, "
                     "now() - %s::interval)", (name, host, budget, age))
    slack = {"slack_s": float(THRESHOLDS["GITHUB_DELIVERY_SLACK_S"])}

    rows = _by_name(conn.execute(plat._ARTIFACTS_SQL, slack).fetchall())
    assert {name: (rows[name][7], rows[name][8], rows[name][10])
            for name in ("w3-gh-held", "w3-gh-stale", "w3-cron-stale")} == {
        "w3-gh-held": (108_000.0, 64_800.0, False),
        "w3-gh-stale": (108_000.0, 64_800.0, True),
        "w3-cron-stale": (2_700.0, 0.0, True),
    }

    by = _by_subject(plat._artifact_cells(conn, THRESHOLDS, _now(conn)))
    assert [by[f"artifact/{name}"]["status"] for name in ("w3-gh-held", "w3-gh-stale", "w3-cron-stale")] == [
        "ok", "fail", "fail"]
