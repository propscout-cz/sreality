"""Emit `frontend/src/lib/filterRegistry.generated.ts` (and `statsRegistry.generated.ts`) from the Python registries.

Single source of truth: `toolkit/filter_registry.py`. This script
reads the in-memory registry and writes a typed TypeScript file the
frontend imports for:

- `<FilterForm>` widget dispatch (uses `ui_control`),
- URL serialisation in `lib/filters.ts` (uses `id` + `type`),
- enum option labels (Czech + English),
- the Settings page's agenda × filter matrix.

Run modes:

- `python scripts/generate_filter_registry.py`  — emit the file.
- `python scripts/generate_filter_registry.py --check` — exit non-zero
  if the on-disk file differs from what we'd generate. Wired into CI
  so a registry edit without a regen fails the build.

The output is committed to the repo so Vite doesn't need to invoke
Python at build time. CI is the drift guard.
"""

from __future__ import annotations

import argparse
import json
import sys
import typing
from pathlib import Path
from typing import Any

from toolkit import filter_registry as fr
from toolkit import stats_registry as sr


HEADER = """\
// AUTOGENERATED — DO NOT EDIT.
// Source of truth: toolkit/filter_registry.py.
// Regenerate with: python scripts/generate_filter_registry.py
//
// CI runs `--check` and fails on drift, so any registry edit must
// be paired with a fresh regen in the same commit.
"""


TS_TYPES = """\
export type Agenda =
{agenda_union}

export type UiControl =
{ui_control_union}

export type FilterType =
{filter_type_union}

export interface EnumOption {{
  value: string | number;
  label_cs: string;
  label_en: string;
  group?: string;
}}

export interface FilterDef {{
  id: string;
  type: FilterType;
  pg_column: string | null;
  default: unknown;
  description: string;
  category: string;
  ui_control: UiControl;
  agendas: Agenda[];
  constraints: Record<string, unknown> | null;
  unit: string | null;
  /** For a filter whose number is a per-m² RATE, the measure that says which
   *  unit it is in — the `unit` string alone is a capital price on a sale
   *  cohort and a MONTHLY rent on a rental one, ~300x apart.
   *  `"depends_on_category"` means the selected category resolves it; null
   *  means the number is an absolute and `unit` labels it completely. See
   *  FilterDef.basis in toolkit/filter_registry.py and CLAUDE.md rule #23. */
  basis: string | null;
  enum_values: EnumOption[] | null;
  aliases: string[];
  /** NULL is a legal "no constraint" value, and the UI must offer a way to
   *  reach it (an explicit "all" pill) — see FilterDef.nullable in
   *  toolkit/filter_registry.py. */
  nullable: boolean;
  /** How a column-backed filter compiles everywhere (toolkit/filter_registry.sql_kind); null = hand-coded per surface. */
  sql_kind: 'eq' | 'any' | 'enum_or_unknown' | 'gte' | 'lte' | null;
}}

export interface FilterRegistryPayload {{
  agendas: Agenda[];
  categories: string[];
  ui_controls: UiControl[];
  filters: FilterDef[];
}}
"""


def _ts_union(values: list[str]) -> str:
    return "\n".join(f'  | "{v}"' for v in values) + ";"


def _render_payload(payload: dict[str, Any]) -> str:
    body = json.dumps(payload, indent=2, ensure_ascii=False)
    return f"export const FILTER_REGISTRY: FilterRegistryPayload = {body};\n"


def _render_helpers() -> str:
    return """\
export function filterById(id: string): FilterDef | undefined {
  return FILTER_REGISTRY.filters.find((f) => f.id === id);
}

export function filtersForAgenda(agenda: Agenda): FilterDef[] {
  return FILTER_REGISTRY.filters.filter((f) => f.agendas.includes(agenda));
}

export const AGENDAS = FILTER_REGISTRY.agendas;
export const CATEGORIES = FILTER_REGISTRY.categories;
export const UI_CONTROLS = FILTER_REGISTRY.ui_controls;
"""


def _render_constants() -> str:
    # Canonical enum tuples emitted from the registry so the frontend's
    # `__unknown__`-sentinel logic (queries.ts enumOrUnknown) reads the SAME
    # values as the SQL RPC / Watchdog / toolkit — one source, no hand-coded
    # duplicate that can silently drift (architectural rule #16).
    def _arr(name: str, values: tuple[str, ...]) -> str:
        items = ", ".join(f'"{v}"' for v in values)
        return f"export const {name} = [{items}] as const;"

    return "\n".join(
        [
            "/* Canonical enum values — single source for the `__unknown__`-sentinel",
            " * multi-select logic (a value that also matches NULL / non-canonical).",
            " * Generated from toolkit.filter_registry; do not hand-edit. */",
            _arr("FURNISHED_CANONICAL", fr.FURNISHED_CANONICAL),
            _arr("OWNERSHIP_CANONICAL", fr.OWNERSHIP_CANONICAL),
            _arr("CONDITION_CANONICAL", fr.COLUMN_CANONICAL_VALUES["condition"]),
            "",
            "/* `listings.price_unit` constrains no filter, so it is not in the payload",
            " * above — but every listing surface renders it after the price, and the",
            " * stored slug ('za mesic') is not the word a Czech page should show. */",
            "export const PRICE_UNIT_LABELS: Record<string, string> = "
            + json.dumps({o.value: o.label_cs for o in fr.PRICE_UNIT_OPTIONS},
                         ensure_ascii=False)
            + ";",
            "",
            "/* building_material bucket -> the building_type values it matches. The one",
            " * expansion is toolkit.filter_registry.building_material_values; Browse reads",
            " * it from here, so Browse and the Watchdog match the same rows (rule 16). */",
            "export const BUILDING_MATERIAL_BUCKETS: Record<string, readonly string[]> = "
            + json.dumps({o.value: fr.building_material_values([o.value])
                          for o in fr.BUILDING_MATERIAL_OPTIONS})
            + ";",
            "",
        ]
    )


def generate() -> str:
    payload = fr.registry_to_json()
    types = TS_TYPES.format(
        agenda_union=_ts_union(payload["agendas"]),
        ui_control_union=_ts_union(payload["ui_controls"]),
        filter_type_union=_ts_union(
            sorted({f["type"] for f in payload["filters"]})
        ),
    )
    return "\n".join(
        [
            HEADER,
            types,
            _render_payload(payload),
            _render_helpers(),
            _render_constants(),
        ]
    )

STATS_HEADER = """\
// AUTOGENERATED — DO NOT EDIT.
// Source of truth: toolkit/stats_registry.py (the Browse > Stats dashboard's vocabulary).
// Regenerate with: python scripts/generate_filter_registry.py
//
// CI runs `--check` and fails on drift. Labels, option order, band steps, category
// availability and the limits live here; the SQL key function and the API validator
// are rendered from the same module, so no face of the registry is hand-restated.
"""

def _stats_types() -> str:
    """The unions and interfaces, every member list read from the registry."""
    def union(values: tuple[str, ...]) -> str:
        return " | ".join(f'"{v}"' for v in values)
    return f"""\
export type DimKind = {union(typing.get_args(sr.DimKind))};
export type MeasureUnit = {union(typing.get_args(sr.MeasureUnit))};
export type StatId = {union(sr.STATS)};
export type ChartStat = {union(sr.CHART_STATS)};
export type ViewId = {union(sr.VIEWS)};
export type StatsRefusal = {union(sr.REFUSALS)};
export type CohortStatus = {union(sr.STATUSES)};

export interface StatsOption {{
  value: string | number;
  label_cs: string;
  label_en: string;
}}

export interface StatsDimension {{
  id: string;
  label_cs: string;
  label_en: string;
  kind: DimKind;
  /** category_main values the dimension exists for; null = every category. */
  categories: string[] | null;
  /** enum / bool: the ordered vocabulary (the ONE order every chart sorts by). */
  options: StatsOption[] | null;
  /** band: the step per basis ({{sale, rent}}) or for every basis ({{all}}); keys are the band's lower bound. */
  steps: Record<string, number> | null;
  /** band: the measure whose values it bands — its unit and its quantity label. */
  measure: string | null;
  /** The palette group, in registry order. */
  group: string;
}}

export interface StatsMeasure {{
  id: string;
  label_cs: string;
  label_en: string;
  unit: MeasureUnit;
  /** ruling 3: the sample must hold one status (active or delisted). */
  single_status: boolean;
}}

export interface StatsViewLimits {{
  min_rows: number;
  max_rows: number;
  max_cols: number;
}}

export interface StatsRegistryPayload {{
  min_n: number;
  max_cells: number;
  max_charts: number;
  chart_stats: ChartStat[];
  default_stat: ChartStat;
  views: ViewId[];
  refusals: StatsRefusal[];
  statuses: CohortStatus[];
  view_limits: Record<ViewId, StatsViewLimits>;
  dimensions: StatsDimension[];
  measures: StatsMeasure[];
}}
"""


def generate_stats() -> str:
    body = json.dumps(sr.registry_json(), indent=2, ensure_ascii=False)
    return "\n".join(
        [
            STATS_HEADER,
            _stats_types(),
            f"export const STATS_REGISTRY: StatsRegistryPayload = {body};\n",
            "export function statsDimension(id: string): StatsDimension | undefined {\n"
            "  return STATS_REGISTRY.dimensions.find((d) => d.id === id);\n}\n",
            "export function statsMeasure(id: string): StatsMeasure | undefined {\n"
            "  return STATS_REGISTRY.measures.find((m) => m.id === id);\n}\n",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Emit frontend/src/lib/filterRegistry.generated.ts and statsRegistry.generated.ts",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Exit non-zero if an on-disk file differs from the "
            "freshly generated content. For CI drift detection."
        ),
    )
    args = parser.parse_args()

    lib = Path(__file__).resolve().parent.parent / "frontend" / "src" / "lib"
    outputs = {
        lib / "filterRegistry.generated.ts": generate(),
        lib / "statsRegistry.generated.ts": generate_stats(),
    }

    status = 0
    for out_path, content in outputs.items():
        if args.check:
            if not out_path.exists():
                print(
                    f"::error::{out_path} is missing; "
                    f"run `python scripts/generate_filter_registry.py` "
                    f"and commit the result.",
                    file=sys.stderr,
                )
                status = 1
            elif out_path.read_text(encoding="utf-8") != content:
                print(
                    f"::error::{out_path} is stale; "
                    f"run `python scripts/generate_filter_registry.py` "
                    f"and commit the result.",
                    file=sys.stderr,
                )
                status = 1
            else:
                print(f"{out_path.name}: up to date")
        else:
            out_path.write_text(content, encoding="utf-8")
            print(f"wrote {out_path}")
    return status


if __name__ == "__main__":
    sys.exit(main())
